/** Each glyph as GLYPH_HEIGHT rows of GLYPH_WIDTH booleans. */
function build() {
  const glyphs = new Map();
  const rows = (lines) => {
    const all = [...lines, ...Array(GLYPH_HEIGHT - lines.length).fill(BLANK)];
    return all.map((line) => [...line].map((c) => c === '#'));
  };
  for (const [char, lines] of Object.entries(SOURCE)) {
    glyphs.set(char, rows(lines));
  }
  for (const [char, [base, accent]] of Object.entries(ACCENTED)) {
    const lines = [...SOURCE[base]];
    lines[0] = ACCENTS[accent][0];
    lines[1] = ACCENTS[accent][1];
    glyphs.set(char, rows(lines));
  }
  glyphs.set('ç', rows([...SOURCE.c, ...CEDILLA]));
  glyphs.set('Ç', rows([...SOURCE.C, ...CEDILLA]));
  return glyphs;
}

export const GLYPHS = build();
