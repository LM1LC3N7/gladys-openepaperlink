/** Accents drawn on rows 0 and 1 of a lower case letter. */
const ACCENTS = {
  acute: ['...#.', '..#..'],
  grave: ['.#...', '..#..'],
  circumflex: ['..#..', '.#.#.'],
  diaeresis: ['.#.#.', BLANK],
  tilde: ['.##.#', '#..#.'],
};
const CEDILLA = ['..#..', '.##..'];

